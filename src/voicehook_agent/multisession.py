def relay_path() -> Path:
    return vact.state_root() / RELAY_NAME


def _h(value: str, salt: str) -> str:
    return hashlib.sha256(f"{salt}|{value}".encode()).hexdigest()[:16]


def session_hash(session_id: object) -> str:
    """Hash of a Claude Code session id ('' when missing): relay.json never holds the id."""
    sid = str(session_id or "").strip()
    return _h(sid, "vh-session") if sid else ""


SESSION_ID_ENVS = ("CLAUDE_CODE_SESSION_ID", "CODEX_THREAD_ID",
                   "OPENCODE_SESSION_ID")  # 0.20.0 Codex CLI, 0.25.0 opencode too


def own_session_id() -> str:
    """Id of the calling agent session: Claude Code (CLAUDE_CODE_SESSION_ID in the Bash tool
    env), else Codex CLI (CODEX_THREAD_ID) or opencode (OPENCODE_SESSION_ID) in its shell
    env, the session_id of its hooks."""
    for name in SESSION_ID_ENVS:
        v = (os.environ.get(name) or "").strip()
        if v:
            return v
    return ""


def own_session_hash() -> str:
    """Hash of the calling agent session (own_session_id), '' outside an agent."""
    return session_hash(own_session_id())


def _token_hash(token: str) -> str:
    return _h(token, "vh-relay-dead")


def machine_label() -> str:
    """Token label: $VOICEHOOK_RELAY_LABEL, else the short host name (max 22, no '|')."""
    raw = (os.environ.get(MACHINE_LABEL_ENV) or "").strip() or socket.gethostname().split(".")[0]
    lbl = re.sub(r"[|:]", " ", vact.scrub(raw))
    lbl = " ".join(lbl.split())[:MACHINE_LABEL_MAX].strip()
    return lbl or "Rechner"


def relay_disabled() -> bool:
    return (os.environ.get(NO_RELAY_ENV) or "").strip().lower() in ("1", "true", "yes", "on")


_LOCAL_HOSTS = ("localhost", "127.0.0.1", "::1")


def _url_ok(url: str) -> bool:
    """https://host/path, or http:// only for localhost / 127.0.0.1 (the token is a Bearer)."""
    from urllib.parse import urlsplit
    m = re.match(r"^(https?)://([^\s/]+)/\S*$", url)
    if not m:
        return False
    if m.group(1) == "https":
        return True
    try:
        host = (urlsplit(url).hostname or "").lower()
    except ValueError:
        return False
    return host in _LOCAL_HOSTS


def write_relay(url: str, token: str, room: str, expires_in: float | None, *,
                owner_pid: int | None = None, owner_session: str | None = None,
                now: float | None = None) -> Path:
    """Write relay.json atomically (tmp + rename, 0600, dir 0700). ValueError on bad input."""
    url = str(url or "").strip()
    if not _url_ok(url):
        raise ValueError("relay url must be https (http only for localhost)")
    if not isinstance(token, str) or not token.strip() or any(c.isspace() for c in token.strip()):
        raise ValueError("relay token missing")
    t = time.time() if now is None else now
    try:
        ttl = float(expires_in) if expires_in is not None else 12 * 3600.0
    except (TypeError, ValueError):
        ttl = 12 * 3600.0
    data = {"url": url, "token": token.strip(), "room": str(room or ""),
            "expires_at": int(t + max(0.0, ttl)),
            "owner_pid": int(os.getpid() if owner_pid is None else owner_pid),
            "owner_session": own_session_hash() if owner_session is None else owner_session,
            "written_at": int(t)}
    vact._private_dir(vact.state_root())
    path = relay_path()
    vact._write_private(path, json.dumps(data))
    try:
        (vact.state_root() / DEAD_NAME).unlink()
    except OSError:
        pass
    return path


LOCAL = "local"
LOCAL_TTL_S = 12 * 3600.0
LOCAL_TAG = vact.RELAY_TOOL  # tool field of a local relay line (server: activity.RELAY_TAG)


def write_local_relay(dir_: Path, room: str, *, label: str | None = None,
                      owner_pid: int | None = None, owner_session: str | None = None,
                      now: float | None = None) -> Path:
    """WebRTC join: relay.json pointing at the join's own session dir (0600, atomic).
    ValueError when dir_ is not a directory."""
    d = Path(dir_).resolve()
    if not d.is_dir():
        raise ValueError("join dir missing")
    t = time.time() if now is None else now
    data = {"kind": LOCAL, "dir": str(d), "label": label or machine_label(),
            "room": str(room or ""), "expires_at": int(t + LOCAL_TTL_S),
            "owner_pid": int(os.getpid() if owner_pid is None else owner_pid),
            "owner_session": own_session_hash() if owner_session is None else owner_session,
            "written_at": int(t)}
    vact._private_dir(vact.state_root())
    path = relay_path()
    vact._write_private(path, json.dumps(data))
    return path


def _is_local(d: dict) -> bool:
    return d.get("kind") == LOCAL


def _read_raw(path: Path | None = None) -> dict | None:
    """relay.json (or a 0.22.2 helper entry) as dict, or None when missing, a symlink, not
    ours, readable by others or not valid."""
    path = relay_path() if path is None else path
    try:
        st = os.lstat(path)
    except OSError:
        return None
    if not stat.S_ISREG(st.st_mode) or st.st_mode & 0o077:
        return None
    if hasattr(os, "getuid") and st.st_uid != os.getuid():
        return None
    try:
        d = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(d, dict):
        return None
    if _is_local(d):
        return d if isinstance(d.get("dir"), str) and os.path.isabs(d["dir"]) else None
    if not isinstance(d.get("token"), str) or not isinstance(d.get("url"), str):
        return None
    if not _url_ok(d["url"]):
        return None  # never send the Bearer over plain http to another host
    return d


DEAD_KEEP = 20  # 0.22.2: relay.dead keeps the hashes of the last dead tokens, one per line


def _dead_hashes() -> list[str]:
    try:
        raw = (vact.state_root() / DEAD_NAME).read_text(encoding="utf-8")
    except OSError:
        return []
    return [x.strip() for x in raw.splitlines() if x.strip()]


def _is_dead(token: str) -> bool:
    return _token_hash(token) in _dead_hashes()


def _usable(d: dict | None, path: Path, t: float) -> dict | None:
    """d when not expired, its owner pid alive and its token not marked dead."""
    if d is None:
        return None
    if "expires_at" not in d and d.get("expires_in") is not None:
        # 0.21.1: a raw `helper-credential` answer copied into relay.json by hand (instead
        # of `helper-import`): valid for expires_in from the file's mtime, no owner
        try:
            d = {**d, "expires_at": os.lstat(path).st_mtime + float(d["expires_in"])}
        except (OSError, TypeError, ValueError):
            return None
    try:
        if float(d.get("expires_at") or 0) <= t:
            return None
        pid = int(d.get("owner_pid") or 0)
    except (TypeError, ValueError):
        return None
    if pid > 0 and not vact._pid_alive(pid):
        return None
    if not _is_local(d) and _is_dead(d["token"]):
        return None
    return d


def load_main_relay(now: float | None = None) -> dict | None:
    """The machine's relay.json (the multi-session relay of a join, or a legacy pre-0.22.2
    `helper-import`): usable (see _read_raw), not expired, owner alive, not marked dead."""
    t = time.time() if now is None else now
    return _usable(_read_raw(), relay_path(), t)


def load_relay(now: float | None = None, *, session: str | None = None) -> dict | None:
    """The relay this session uses (0.22.2): its OWN helper entry (helpers/<name>.json, see
    load_helper) first, else relay.json (load_main_relay). `session` = session hash of the
    caller (the hook passes the one of its event); default the calling agent session."""
    h = load_helper(now, session=session)
    return h if h is not None else load_main_relay(now)


def is_legacy_helper(d: object) -> bool:
    """A pre-0.22.2 `helper-import` in relay.json: ONE credential for every session of the
    machine (the last import won for all). Remote, no owner pid, no owner session."""
    return (isinstance(d, dict) and not d.get("helper") and not _is_local(d)
            and not int(d.get("owner_pid") or 0) and not d.get("owner_session"))


LEGACY_WARN = ("[warn] ~/.voicehook/relay.json is a shared helper credential (helper-import "
               "before 0.22.2): every helper session of this machine posts under its one "
               "sender. Import one per session: `... | voicehook-agent helper-import --as <name>`")


