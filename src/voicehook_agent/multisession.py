def _with_state(fn) -> object:
    vact._private_dir(vact.state_root())
    path = vact.state_root() / STATE_NAME
    fd = os.open(path, os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0), 0o600)
    try:
        vact._lock(fd)
        try:
            st = json.loads(os.read(fd, 1 << 18).decode("utf-8") or "{}")
        except ValueError:
            st = {}
        if not isinstance(st, dict):
            st = {}
        res = fn(st)
        os.lseek(fd, 0, os.SEEK_SET)
        os.ftruncate(fd, 0)
        os.write(fd, json.dumps(st).encode("utf-8"))
        return res
    finally:
        os.close(fd)


def _admit(skey: str, kind: str, text: str, event: dict, t: float) -> str | None:
    """Throttle under the state lock. The final line or None (dropped)."""
    def step(st: dict):
        sessions = st.get("sessions") if isinstance(st.get("sessions"), dict) else {}
        posts = [p for p in (st.get("posts") or []) if isinstance(p, (int, float))
                 and t - p < GLOBAL_WINDOW_S]
        me = sessions.get(skey) if isinstance(sessions.get(skey), dict) else {}
        label = session_label(event, str(me.get("label") or ""))
        line = vact.scrub(f"{label}: {text}")[:TEXT_MAX].strip()
        me["label"] = label
        # 0.32.0 (watch.py): what the session did last, also when the line is throttled below
        me.update(ev=kind, ev_text=text[:60], ev_at=t)
        tp = event.get("transcript_path")
        if isinstance(tp, str) and tp:
            me["tp"] = tp[:512]
        sessions.pop(skey, None)
        keep = sorted(((k, v) for k, v in sessions.items() if isinstance(v, dict)),
                      key=lambda kv: float(kv[1].get("at") or 0))[-(SESSIONS_KEEP - 1):]
        st["sessions"] = {**dict(keep), skey: me}
        st["posts"] = posts
        if me.get("last") == line and t - float(me.get("at") or 0) < DEDUPE_S:
            return None
        if kind not in IMPORTANT and t - float(me.get("low_at") or 0) < LOW_GAP_S:
            return None
        if len(posts) >= (GLOBAL_MAX_IMPORTANT if kind in IMPORTANT else GLOBAL_MAX):
            return None
        me.update(last=line, at=t)
        if kind not in IMPORTANT:
            me["low_at"] = t
        posts.append(t)
        return line
    return _with_state(step)


def note_helper_session(label: str, env=None, t: float | None = None) -> None:
    """0.32.2 (watch.py): a helper command (status, activity, decide, show over the relay)
    runs inside an agent session. Remember label -> transcript of that session in the
    registry, so the watcher can observe sessions that have no hooks installed (helper-import
    only). Claude Code only (CLAUDE_CODE_SESSION_ID). Best effort, never raises."""
    env = os.environ if env is None else env
    sid = str(env.get("CLAUDE_CODE_SESSION_ID") or "").strip()
    if not sid or not label or "/" in sid or sid.startswith("."):
        return
    try:
        from . import relayops as vrelayops  # relayops imports this module

        hits = sorted((vrelayops._config_dir() / "projects").glob(f"*/{sid}.jsonl"))
    except Exception:  # noqa: BLE001
        return
    if not hits:
        return
    now = time.time() if t is None else t
    skey = session_hash(sid)

    def step(st: dict) -> None:
        sessions = st.get("sessions") if isinstance(st.get("sessions"), dict) else {}
        me = sessions.get(skey) if isinstance(sessions.get(skey), dict) else {}
        me.update(label=label[:SESSION_LABEL_MAX], tp=str(hits[0])[:512], seen_at=now)
        sessions.pop(skey, None)
        keep = sorted(((k, v) for k, v in sessions.items() if isinstance(v, dict)),
                      key=lambda kv: float(kv[1].get("at") or kv[1].get("seen_at") or 0))
        st["sessions"] = {**dict(keep[-(SESSIONS_KEEP - 1):]), skey: me}
    with contextlib.suppress(Exception):
        _with_state(step)


POST_RETRY_503_S = (1.0, 2.0)  # 0.22.2: the detached child retries a 503 (never dead)


def post_line(text: str, timeout: float = POST_TIMEOUT_S, *,
              session: str | None = None, retry_503: tuple = ()) -> int | None:
    """POST {text} to the relay of this session (load_relay: own helper entry, else
    relay.json; Bearer, never in the URL). HTTP status (None: no relay / network error).
    401/403/410 mark the token dead."""
    import urllib.error
    import urllib.request
    rel = load_relay(session=session)
    if rel is None or _is_local(rel):
        return None
    for wait in (*retry_503, None):
        req = urllib.request.Request(
            rel["url"], method="POST",
            data=json.dumps({"text": text}, ensure_ascii=False).encode("utf-8"),
            headers={"authorization": f"Bearer {rel['token']}", "content-type": "application/json",
                     "user-agent": "voicehook-agent-hook"})
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:  # url from our own 0600 file
                status = r.status
        except urllib.error.HTTPError as e:
            status = e.code
        except Exception:  # noqa: BLE001
            return None
        if status != 503 or wait is None:
            break
        time.sleep(wait)  # 0.22.2: 503 = main agent briefly away (v4 #586): wait, retry
    if status in (401, 403, 410):
        mark_dead(rel["token"])
    return status


def _spawn_post(text: str, session: str = "") -> None:
    """Detached `voicehook-agent-hook relay-post` (text on stdin, never argv), isolated
    from the cwd of the reporting session (vact.child_argv: -I, cwd = state dir)."""
    import subprocess
    try:
        p = subprocess.Popen(vact.child_argv("relay-post"),
                             stdin=subprocess.PIPE, stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL, start_new_session=True,
                             cwd=vact.child_cwd())
        assert p.stdin is not None
        p.stdin.write(json.dumps({"text": text, **({"session": session} if session else {})})
                      .encode("utf-8"))
        p.stdin.close()
    except Exception:  # noqa: BLE001
        return


def append_local(rel: dict, line: str, now: float | None = None) -> bool:
    """Local relay: append `HH:MM:SS relay: Helfer <machine>: <line>` to the activity.log of
    the join named by rel (only when its session.json names the owner pid). Never raises."""
    try:
        d = Path(str(rel.get("dir") or ""))
        st = os.lstat(d)
        if not stat.S_ISDIR(st.st_mode) or (hasattr(os, "getuid") and st.st_uid != os.getuid()):
            return False
        info = json.loads((d / vact.vsession.INFO_NAME).read_text(encoding="utf-8"))
        if int(info.get("pid") or 0) != int(rel.get("owner_pid") or -1):
            return False
        label = re.sub(r"[|:]", " ", vact.scrub(str(rel.get("label") or ""))).strip() or "Rechner"
        body = vact.scrub(f"Helfer {label}: {line}")[:vact.DESC_MAX].strip()
        vact.append_line(d, f"{vact._ts(now)} {LOCAL_TAG}: {body}")
        return True
    except Exception:  # noqa: BLE001
        return False


def relay_post_main(raw: str) -> int:
    """The detached child: post one line. Always 0."""
    try:
        d = json.loads(raw or "{}")
        text = str(d.get("text") or "") if isinstance(d, dict) else ""
        skey = str(d.get("session") or "") if isinstance(d, dict) else ""
        if text and skey:  # 0.22.2: the helper entry of that session
            post_line(text, session=skey, retry_503=POST_RETRY_503_S)
        elif text:
            post_line(text, retry_503=POST_RETRY_503_S)
    except Exception:  # noqa: BLE001, S110 - detached child, nobody to tell
        pass
    return 0


def handle_event(raw: str, now: float | None = None, post=None) -> str | None:
    """Hook entry: the line handed to `post` (default: detached POST) or None. Silent
    without relay.json, for the joining session itself, and on anything unexpected."""
    try:
        if os.environ.get("VOICEHOOK_WATCH_CHILD"):
            return None  # the watcher's own model call is no session
        event = json.loads(raw) if raw and raw.strip() else {}
        if not isinstance(event, dict):
            return None
        sess = session_hash(event.get("session_id")) or own_session_hash()
        rel = load_relay(now, session=sess)  # 0.22.2: own helper entry first
        if rel is None:
            return None
        skey = sess or "cwd-" + _h(str(event.get("cwd") or ""), "vh-cwd")
        own = str(rel.get("owner_session") or "")
        if own and own == skey and not rel.get("helper"):
            return None  # the joining session: its own hook already feeds the call
        got = classify(event)
        if got is None:
            return None
        kind, text = got
        line = _admit(skey, kind, text, event, time.time() if now is None else now)
        if not line:
            return None
        if post is not None:
            post(line)
        elif _is_local(rel):
            append_local(rel, line)
        elif rel.get("helper"):
            _spawn_post(line, sess)  # 0.22.2: the child loads the same helper entry
        else:
            _spawn_post(line)
        return line
    except Exception:  # noqa: BLE001 - a hook must never disturb Claude Code
        return None
