def helpers_dir() -> Path:
    return vact.state_root() / HELPERS_DIR


def helper_key(name: object) -> str:
    """File name of a helper entry: [A-Za-z0-9._-], max 40 chars, '' when nothing is left."""
    k = re.sub(r"[^A-Za-z0-9._-]+", "-", str(name or "").strip()).strip("-.")
    return k[:SESSION_LABEL_MAX].strip("-.")


def _helper_entries() -> list[tuple[Path, dict]]:
    """All valid helper entries (path, data), sorted by name. Never raises."""
    d = helpers_dir()
    try:
        st = os.lstat(d)
        if not stat.S_ISDIR(st.st_mode) or (hasattr(os, "getuid") and st.st_uid != os.getuid()):
            return []
        names = sorted(os.listdir(d))
    except OSError:
        return []
    out: list[tuple[Path, dict]] = []
    for n in names:
        if not n.endswith(".json"):
            continue
        p = d / n
        e = _read_raw(p)
        if e is not None and not _is_local(e) and e.get("helper") == n[:-5]:
            out.append((p, e))
    return out


def write_helper(name: str, url: str, token: str, room: str, expires_in: float | None, *,
                 owner_session: str | None = None, label: str = "",
                 now: float | None = None) -> Path:
    """helpers/<key>.json (0600, dir 0700, atomic): the credential of ONE helper session.
    owner_session (default: the calling agent session, '' outside one) binds it to that
    session; another entry bound to the same session is removed. ValueError on bad input."""
    key = helper_key(name)
    if not key:
        raise ValueError("helper-import: no name (pass --as <name>)")
    url = str(url or "").strip()
    if not _url_ok(url):
        raise ValueError("relay url must be https (http only for localhost)")
    if not isinstance(token, str) or not token.strip() or any(c.isspace() for c in token.strip()):
        raise ValueError("relay token missing")
    t = time.time() if now is None else now
    try:
        ttl = float(expires_in) if expires_in is not None else 12 * 3600.0
    except (TypeError, ValueError):
        ttl = 12 * 3600.0
    owner = own_session_hash() if owner_session is None else str(owner_session or "")
    data = {"helper": key, "url": url, "token": token.strip(), "room": str(room or ""),
            "label": str(label or "")[:MACHINE_LABEL_MAX], "expires_at": int(t + max(0.0, ttl)),
            "owner_pid": 0, "owner_session": owner, "written_at": int(t)}
    vact._private_dir(vact.state_root())
    vact._private_dir(helpers_dir())
    path = helpers_dir() / f"{key}.json"
    if owner:
        for other, e in _helper_entries():
            if other != path and e.get("owner_session") == owner:
                try:
                    other.unlink()
                except OSError:
                    pass
    vact._write_private(path, json.dumps(data))
    return path


def own_helper_entry(*, session: str | None = None) -> tuple[Path, dict] | None:
    """(path, data) of the helper entry of THIS session in any state (also dead or expired),
    never the one of another session:
    1. $VOICEHOOK_SESSION_LABEL names an entry (helpers/<key of the label>.json),
    2. else an entry bound to this session (owner_session = session hash: `helper-import`
       ran inside this session),
    3. else the only entry bound to no session (imported over ssh, outside any session:
       `helper-import --as <name>`); with several unbound entries: none (ambiguous)."""
    entries = _helper_entries()
    if not entries:
        return None
    skey = own_session_hash() if session is None else str(session or "")
    want = helper_key(os.environ.get(LABEL_ENV))
    if want:
        for p, e in entries:
            if e.get("helper") == want:
                return p, e
    if skey:
        for p, e in entries:
            if e.get("owner_session") == skey:
                return p, e
    free = [(p, e) for p, e in entries if not e.get("owner_session")]
    if len(free) == 1:
        return free[0]
    # 0.24.x: imported helper (helper-import wrote helpers/<name>.json with an owner_session
    # bound to the importing session, never relay.json). When the hook fires without a
    # VOICEHOOK_SESSION_LABEL and with a session hash that does not match the stored
    # owner_session (own VOICEHOOK_STATE_DIR per helper = unambiguous), use the single
    # usable entry even though it is bound to a different session. Only when no relay.json
    # exists: if relay.json is present the main agent handles other-session routing via
    # load_main_relay and the single-entry fallback must not hijack that path.
    if load_main_relay() is not None:
        return None
    t = time.time()
    usable = [(p, e) for p, e in entries if _usable(e, p, t) is not None]
    return usable[0] if len(usable) == 1 else None


def helper_state(entry: dict, path: Path | None = None, now: float | None = None) -> str:
    """0.25.0: 'live', 'dead' (token marked in relay.dead: 401/403/410, e.g. the main agent
    rejoined), 'expired' or 'unusable' (bad, or owner gone) for one helper entry. The same
    rules as _usable (an entry with only expires_in counts from the file's mtime; relay.dead
    applies to remote entries only), so 'live' here == load_helper takes it."""
    t = time.time() if now is None else now
    p = helpers_dir() if path is None else path
    if _usable(entry, p, t) is not None:
        return "live"
    if not _is_local(entry) and isinstance(entry.get("token"), str) and _is_dead(entry["token"]):
        return "dead"
    try:
        if "expires_at" not in entry and entry.get("expires_in") is not None:
            exp = os.lstat(p).st_mtime + float(entry["expires_in"])
        elif entry.get("expires_at") is None:
            return "unusable"
        else:
            exp = float(entry.get("expires_at") or 0)
    except (OSError, TypeError, ValueError):
        return "unusable"
    return "expired" if exp <= t else "unusable"


def load_helper(now: float | None = None, *, session: str | None = None) -> dict | None:
    """The usable helper entry of THIS session (own_helper_entry), never the one of another
    session. None otherwise (load_relay then takes relay.json)."""
    found = own_helper_entry(session=session)
    if found is None:
        return None
    t = time.time() if now is None else now
    return _usable(found[1], found[0], t)


def mark_dead(token: str) -> None:
    """401/403/410 from the relay: readers skip this token. The file stays (not ours)."""
    try:
        vact._private_dir(vact.state_root())
        h = _token_hash(token)
        keep = [x for x in _dead_hashes() if x != h][-(DEAD_KEEP - 1):] + [h]
        vact._write_private(vact.state_root() / DEAD_NAME, "\n".join(keep))
    except OSError:
        pass


def remove_relay(*, owner_pid: int | None = None, owner_session: str | None = None,
                 room: str | None = None) -> bool:
    """Owner cleanup: remove relay.json only if it still names this owner (pid or session
    hash) and, when given, this room. True if removed. Never raises."""
    try:
        d = _read_raw()
        if d is None:
            return False
        mine = (owner_pid is not None and int(d.get("owner_pid") or 0) == int(owner_pid)) or \
               (bool(owner_session) and d.get("owner_session") == owner_session)
        if not mine or (room is not None and str(d.get("room") or "") != str(room)):
            return False
        relay_path().unlink()
        for name in (DEAD_NAME, STATE_NAME):
            try:
                (vact.state_root() / name).unlink()
            except OSError:
                pass
        return True
    except Exception:  # noqa: BLE001
        return False


def relay_from_answer(answer: object) -> dict | None:
    """A join answer that carries a relay token: {relay: {token, url, expires_in}} or the
    mint answer itself {token, url, expires_in}."""
    if not isinstance(answer, dict):
        return None
    r = answer.get("relay") if isinstance(answer.get("relay"), dict) else answer
    if isinstance(r.get("token"), str) and isinstance(r.get("url"), str) and r["token"] and r["url"]:
        return {"token": r["token"], "url": r["url"], "expires_in": r.get("expires_in")}
    return None


def mint_relay(base: str, session: str, label: str | None = None,
               timeout: float = MINT_TIMEOUT_S) -> dict | None:
    """POST <base>/api/bridge/activity/relay-token {label} with the bridge session.
    The answer {token, url, expires_in} or None. Never raises."""
    import urllib.error
    import urllib.request
    base = str(base or "").rstrip("/")
    if not re.match(r"^https?://[^\s/]+", base) or not session:
        return None
    req = urllib.request.Request(
        base + MINT_PATH, method="POST",
        data=json.dumps({"label": label or machine_label()}).encode("utf-8"),
        headers={"authorization": f"Bearer {session}", "content-type": "application/json",
                 "user-agent": "voicehook-agent"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:  # base from our own 0600 file / CLI arg
            return relay_from_answer(json.loads(r.read().decode("utf-8")))
    except Exception:  # noqa: BLE001
        return None


