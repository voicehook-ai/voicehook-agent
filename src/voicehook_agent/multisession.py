_SHELLS = {"bash", "sh", "zsh", "dash", "ksh"}
_HEREDOC = re.compile(r"(?<!<)<<(?!<)(-?)\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\2")
_QUOTED = re.compile(r"'[^']*(?:'|$)|\"(?:[^\"\\]|\\.)*(?:\"|$)", re.DOTALL)
_ENV_ASSIGN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
_DEPLOY_RX = re.compile(
    r"(?:^|[\s/])(?:"
    r"(?:wrangler|vercel|netlify|firebase|fly|flyctl|railway|serverless|sls|cdk|amplify)\b[^\n]*\bdeploy\b"
    r"|supabase\s+(?:functions|db)\s+(?:deploy|push)\b"
    r"|(?:npm|pnpm|yarn|bun)\s+(?:run\s+)?deploy\b"
    r"|make\s+deploy\b"
    r"|[\w.\-]*deploy[\w.\-]*\.sh\b"
    r"|vercel\s+--prod\b"
    r"|kubectl\s+(?:apply|rollout)\b"
    r"|helm\s+(?:upgrade|install)\b"
    r"|gh\s+workflow\s+run\s+[\w.\-]*deploy"
    r")")
_PR_CREATE = re.compile(r"\bgh\s+pr\s+create\b")
_PR_MERGE = re.compile(r"\bgh\s+pr\s+merge\b")
_PR_URL = re.compile(r"/pull/(\d{1,7})\b")
_PR_HASH = re.compile(r"#(\d{1,7})\b")


def _strip_heredocs(command: str) -> str:
    """Drop heredoc bodies (`<<EOF ... EOF`, `<<-'X' ... X`): a commit message or a file
    written by cat is text, not a command."""
    out: list[str] = []
    pending: list[tuple[str, bool]] = []
    for line in command.split("\n"):
        if pending:
            delim, dash = pending[0]
            if (line.lstrip("\t") if dash else line).strip() == delim:
                pending.pop(0)
            continue
        out.append(line)
        pending.extend((m.group(3), bool(m.group(1))) for m in _HEREDOC.finditer(line))
    return "\n".join(out)


def _unquote(command: str) -> str:
    """Command text without heredoc bodies and without anything in quotes ('' / ""):
    only the words the shell runs are matched, never a message or an argument text."""
    return _QUOTED.sub("''", _strip_heredocs(str(command or "")))


def _segments(command: str) -> list[str]:
    out = []
    for seg in _SEG_SPLIT.split(_unquote(command)):
        words = [w for w in seg.strip().split() if not _ENV_ASSIGN.match(w)]
        if words and words[0].rsplit("/", 1)[-1] not in _READONLY:
            out.append(" ".join(words))
    return out


def _dry(seg: str) -> bool:
    """A segment that only checks: `--dry-run` / `--dryrun`, or `bash -n x.sh`."""
    words = seg.split()
    if any(w.startswith(("--dry-run", "--dryrun")) for w in words):
        return True
    if words and words[0].rsplit("/", 1)[-1] in _SHELLS:
        for w in words[1:]:
            if not w.startswith("-"):
                break
            if w.startswith("-") and not w.startswith("--") and "n" in w[1:]:
                return True
    return False


_WORKFLOW_RUN = re.compile(r"\bgh\s+workflow\s+run\b")


def _deploy_kind(command: str) -> str:
    """'' (no deploy), 'triggered' (`gh workflow run *deploy*`: only started) or 'ran'."""
    kind = ""
    for s in _segments(command):
        if _dry(s) or not _DEPLOY_RX.search(" " + s):
            continue
        if not _WORKFLOW_RUN.search(s):
            return "ran"
        kind = "triggered"
    return kind


def _is_deploy(command: str) -> bool:
    return bool(_deploy_kind(command))


def _merge_mode(command: str) -> str:
    """'merge', 'auto' (`--auto`: only queued), 'off' (`--disable-auto`) for the first
    `gh pr merge` segment."""
    for s in _segments(command):
        if _PR_MERGE.search(s):
            words = s.split()
            if "--disable-auto" in words:
                return "off"
            return "auto" if "--auto" in words else "merge"
    return "merge"


def _has(rx: re.Pattern, command: str) -> bool:
    return any(rx.search(s) for s in _segments(command))


def _output(resp: object) -> str:
    if isinstance(resp, str):
        return resp[:20000]
    if isinstance(resp, dict):
        return " ".join(str(resp.get(k) or "") for k in ("stdout", "stderr", "output", "result",
                                                          "url", "html_url"))[:20000]
    if isinstance(resp, list):
        return " ".join(str(x.get("text") or "") if isinstance(x, dict) else str(x)
                        for x in resp)[:20000]
    return ""


def _resp_failed(resp: object) -> bool:
    if not isinstance(resp, dict):
        return False
    if resp.get("is_error") is True or resp.get("isError") is True:
        return True
    for k in ("exit_code", "exitCode", "returncode", "code"):
        v = resp.get(k)
        if isinstance(v, int) and not isinstance(v, bool) and v != 0:
            return True
    return False


def _merge_arg(command: str) -> str:
    """The PR number argument of `gh pr merge` (word by word, no backtracking regex)."""
    for seg in _segments(command):
        words = seg.split()
        for i in range(len(words) - 2):
            if words[i:i + 3] == ["gh", "pr", "merge"]:
                for w in words[i + 3:]:
                    if re.fullmatch(r"#?\d{1,7}", w):
                        return w.lstrip("#")
    return ""


def _pr_number(command: str, out: str, merge: bool) -> str:
    num = _merge_arg(command) if merge else ""
    if num:
        return f"PR #{num}"
    m = _PR_URL.search(_unquote(command) if merge else "") or _PR_URL.search(out) \
        or (_PR_HASH.search(out) if merge else None)
    return f"PR #{m.group(1)}" if m else "PR"


def classify(event: dict) -> tuple[str, str] | None:
    """(kind, text) for one hook event, or None (nothing to report). kind in
    turn/stop/pr/deploy/error."""
    name = str(event.get("hook_event_name") or "")
    if name == "UserPromptSubmit":
        return "turn", prompt_goal(event.get("prompt"))
    if name == "Stop":
        return "stop", "Turn fertig"
    if name in ("Notification", "PermissionRequest", "PreToolUse"):
        # 0.18.0: the session waits for the human (notify.py); the question itself goes
        # to the Decision Board, the feed only says that it waits
        from . import notify
        info = notify.classify(event)
        return ("wait", info["text"]) if info and info.get("text") else None
    if name not in ("PostToolUse", "PostToolUseFailure"):
        return None
    tool = vact.sanitize_tool(event.get("tool_name"))
    inp = event.get("tool_input") if isinstance(event.get("tool_input"), dict) else {}
    resp = event.get("tool_response")
    failed = name == "PostToolUseFailure" or _resp_failed(resp)
    if name == "PostToolUseFailure" and event.get("is_interrupt") is True:
        return None  # the user pressed Esc: no error worth a line
    low = tool.lower()
    if tool == "Bash":
        cmd = str(inp.get("command") or "")
        out = _output(resp)
        if _has(_PR_MERGE, cmd):
            pr = _pr_number(cmd, out, merge=True)
            mode = _merge_mode(cmd)
            if mode == "off":
                return None
            if mode == "auto":
                return ("error", f"{pr} Auto-Merge fehlgeschlagen") if failed \
                    else ("pr", f"{pr} Auto-Merge an")
            return ("error", f"{pr} Merge fehlgeschlagen") if failed else ("pr", f"{pr} gemergt")
        if _has(_PR_CREATE, cmd):
            if failed:
                return "error", "PR erstellen fehlgeschlagen"
            return "pr", f"{_pr_number(cmd, out, merge=False)} geöffnet"
        dep = _deploy_kind(cmd)
        if dep:
            if failed:
                return "error", "Deploy fehlgeschlagen"
            return "deploy", "Deploy angestoßen" if dep == "triggered" else "Deploy gelaufen"
    elif "pull_request" in low and ("create" in low or "merge" in low):
        out = _output(resp) if not isinstance(resp, dict) else json.dumps(resp)[:20000]
        m = _PR_URL.search(out) or re.search(r'"number":\s*(\d{1,7})', out)
        if m is None and "merge" in low:
            m = re.search(r"^(\d{1,7})$", str(inp.get("pullNumber") or inp.get("pull_number") or ""))
        pr = f"PR #{m.group(1)}" if m else "PR"
        verb = "gemergt" if "merge" in low else "geöffnet"
        return ("error", f"{pr} {'Merge' if 'merge' in low else 'erstellen'} fehlgeschlagen") \
            if failed else ("pr", f"{pr} {verb}")
    if failed:
        # tool name only: neither the error text nor the tool's description (it can name
        # customers, files or plans of another session)
        return "error", f"Fehler bei {tool}"
    return None


